-- MRS Exam role-based permissions (Dell-mac / mrsexam)
-- Do not SELECT passwords.

IF COL_LENGTH('dbo.USERS', 'ROLE') IS NULL
  ALTER TABLE dbo.USERS ADD ROLE nvarchar(20) NULL;
GO

IF OBJECT_ID('dbo.USER_EXAM', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.USER_EXAM (
    USERID nvarchar(10) NOT NULL,
    EXAM_CODE nvarchar(20) NOT NULL,
    CONSTRAINT PK_USER_EXAM PRIMARY KEY (USERID, EXAM_CODE)
  );
END;
GO

IF OBJECT_ID('dbo.USER_CENTRE', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.USER_CENTRE (
    USERID nvarchar(10) NOT NULL,
    CENTRE_NO nvarchar(20) NOT NULL,
    CONSTRAINT PK_USER_CENTRE PRIMARY KEY (USERID, CENTRE_NO)
  );
END;
GO

UPDATE dbo.USERS SET ROLE = N'SUPER' WHERE UPPER(RTRIM(USERID)) = N'SUPER';
UPDATE dbo.USERS SET ROLE = N'OPERATOR' WHERE ROLE IS NULL AND UPPER(RTRIM(USERID)) <> N'SUPER';
GO

